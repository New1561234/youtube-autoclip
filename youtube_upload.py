"""
YouTube upload helper (resumable upload via the YouTube Data API v3).

This module is intentionally thin: it takes already-authenticated credentials
(see ``youtube_auth``) and pushes a file the app itself generated.

Google client libraries are imported lazily so the rest of the clipper keeps
working when the optional dependencies are absent.
"""

import os

# Resumable uploads must use a chunk size that is a multiple of 256 KiB.
UPLOAD_CHUNK_SIZE = 5 * 1024 * 1024  # 5 MiB

ALLOWED_PRIVACY = ("private", "unlisted", "public")

# YouTube's default category id for "Entertainment".
DEFAULT_CATEGORY_ID = "24"


class YouTubeUploadError(Exception):
    """Raised for user-facing upload problems. ``args[0]`` is a safe message."""


def _import_http():
    try:
        from googleapiclient.discovery import build
        from googleapiclient.http import MediaFileUpload
    except Exception as exc:
        raise YouTubeUploadError(
            "Google API libraries are not installed. Run: pip install -r requirements.txt"
        ) from exc
    return build, MediaFileUpload


def _guess_mimetype(path):
    ext = os.path.splitext(path)[1].lower()
    return {
        ".mp4": "video/mp4",
        ".mov": "video/quicktime",
        ".webm": "video/webm",
        ".mkv": "video/x-matroska",
        ".avi": "video/x-msvideo",
    }.get(ext, "video/*")


def upload_video(credentials, file_path, title, description="",
                 privacy_status="private", progress_cb=None):
    """Upload ``file_path`` to YouTube and return the new video's details.

    Parameters
    ----------
    credentials : google.oauth2.credentials.Credentials
        Authenticated credentials with the ``youtube.upload`` scope.
    file_path : str
        Path to the MP4 generated by this app.
    title : str
        Video title (required by YouTube, max 100 chars).
    description : str
        Optional description (max 5000 chars).
    privacy_status : str
        One of "private", "unlisted", "public". Defaults to "private".
    progress_cb : callable, optional
        Called with an int percentage (0-100) as the upload progresses.

    Returns
    -------
    dict
        ``{"video_id": str, "url": str, "title": str}``
    """
    if not os.path.isfile(file_path):
        raise YouTubeUploadError("File not found")

    title = (title or "").strip()
    if not title:
        raise YouTubeUploadError("A title is required")
    if len(title) > 100:
        raise YouTubeUploadError("Title must be 100 characters or fewer")

    description = description or ""
    if len(description) > 5000:
        raise YouTubeUploadError("Description must be 5000 characters or fewer")

    if privacy_status not in ALLOWED_PRIVACY:
        raise YouTubeUploadError("Invalid privacy setting")

    build, MediaFileUpload = _import_http()

    body = {
        "snippet": {
            "title": title,
            "description": description,
            "categoryId": DEFAULT_CATEGORY_ID,
        },
        "status": {
            "privacyStatus": privacy_status,
            "selfDeclaredMadeForKids": False,
        },
    }

    try:
        youtube = build("youtube", "v3", credentials=credentials, cache_discovery=False)
        media = MediaFileUpload(
            file_path,
            mimetype=_guess_mimetype(file_path),
            chunksize=UPLOAD_CHUNK_SIZE,
            resumable=True,
        )
        request = youtube.videos().insert(
            part="snippet,status",
            body=body,
            media_body=media,
        )

        response = None
        while response is None:
            status, response = request.next_chunk()
            if status is not None and progress_cb is not None:
                try:
                    progress_cb(int(round(status.progress() * 100)))
                except Exception:
                    pass
    except YouTubeUploadError:
        raise
    except Exception as exc:
        # Normalise any transport/API error into a safe message. The raw error
        # can contain request internals we do not want to surface to the browser.
        raise YouTubeUploadError(_safe_error_message(exc)) from exc

    if progress_cb is not None:
        try:
            progress_cb(100)
        except Exception:
            pass

    video_id = (response or {}).get("id")
    if not video_id:
        raise YouTubeUploadError("Upload finished but YouTube did not return a video id")

    return {
        "video_id": video_id,
        "url": "https://youtu.be/" + video_id,
        "title": title,
    }


def _safe_error_message(exc):
    """Extract a short, non-sensitive message from an API/transport error."""
    # googleapiclient.errors.HttpError carries a JSON body with a human message.
    try:
        from googleapiclient.errors import HttpError
        if isinstance(exc, HttpError):
            content = exc.content
            if isinstance(content, bytes):
                content = content.decode("utf-8", "ignore")
            parsed = json_loads(content)
            if isinstance(parsed, dict):
                err = parsed.get("error", {})
                if isinstance(err, dict):
                    msg = err.get("message") or err.get("status")
                    if msg:
                        return _truncate(msg)
    except Exception:
        pass
    return _truncate(str(exc) or "Upload failed")


def _truncate(text, limit=180):
    text = " ".join(str(text).split())
    return text[:limit] if len(text) > limit else text


def json_loads(text):
    import json
    try:
        return json.loads(text)
    except Exception:
        return {}